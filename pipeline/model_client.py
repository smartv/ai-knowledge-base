class LLMError(RuntimeError):
    """Error raised for LLM API failures.

    Attributes:
        status_code: HTTP status code when the failure came from the API.
        retryable: Whether the caller may retry the request.
    """

    def __init__(
        self,
        message: str,
        *,
        status_code: int | None = None,
        retryable: bool = False,
    ) -> None:
        """Initialize the error.

        Args:
            message: Human-readable error message.
            status_code: HTTP status code, if any.
            retryable: Whether the failure is considered transient.
        """
        super().__init__(message)
        self.status_code = status_code
        self.retryable = retryable


def estimate_tokens(text: str) -> int:
    """Estimate tokens for mixed Chinese/English text.

    The heuristic counts one token per non-ASCII character and roughly four
    ASCII characters per token. It is intentionally rough; prefer the usage
    block returned by the API when it is available.

    Args:
        text: Input text.

    Returns:
        Estimated token count.
    """
    if not text:
        return 0

    ascii_chars = sum(1 for char in text if char.isascii())
    non_ascii_chars = len(text) - ascii_chars
    return max(1, math.ceil(ascii_chars / 4) + non_ascii_chars)


def estimate_messages_tokens(messages: Sequence[Message]) -> int:
    """Estimate prompt tokens for a list of chat messages.

    Args:
        messages: OpenAI-format chat messages.

    Returns:
        Estimated prompt token count, including per-message overhead.
    """
    total = 2
    for message in messages:
        total += 4
        total += estimate_tokens(str(message.get("content", "")))
    return total


def calculate_cost(
    usage: Usage,
    input_per_1m_usd: float,
    output_per_1m_usd: float,
) -> float:
    """Calculate USD cost from token usage and per-million prices.

    Args:
        usage: Token usage for the call.
        input_per_1m_usd: Input price per one million tokens in USD.
        output_per_1m_usd: Output price per one million tokens in USD.

    Returns:
        Estimated cost in USD.

    Raises:
        ValueError: If either price is negative.
    """
    if input_per_1m_usd < 0 or output_per_1m_usd < 0:
        raise ValueError("token 单价不能为负数")

    return (
        usage.prompt_tokens * input_per_1m_usd
        + usage.completion_tokens * output_per_1m_usd
    ) / 1_000_000


def estimate_cost(
    provider_name: str,
    usage: Usage,
    model: str | None = None,
) -> float:
    """Estimate USD cost for a provider and model.

    Args:
        provider_name: Provider identifier, e.g. ``deepseek``.
        usage: Token usage for the call.
        model: Model name; defaults to the provider's default model.

    Returns:
        Estimated cost in USD.

    Raises:
        ValueError: If the provider is unknown.
    """
    name = provider_name.strip().lower()
    spec = PROVIDER_SPECS.get(name)
    if spec is None:
        supported = ", ".join(sorted(PROVIDER_SPECS))
        raise ValueError(f"未知 provider: {provider_name!r}，可选: {supported}")

    model_name = model or spec.default_model
    pricing = spec.pricing.get(model_name)
    if pricing is None:
        LOGGER.warning(
            "未知模型 %s，使用默认模型 %s 的价格估算",
            model_name,
            spec.default_model,
        )
        pricing = spec.pricing[spec.default_model]

    return calculate_cost(
        usage,
        pricing.input_per_1m_usd,
        pricing.output_per_1m_usd,
    )


class LLMProvider(ABC):
    """Abstract interface for an LLM provider."""

    @property
    @abstractmethod
    def name(self) -> str:
        """Return the provider identifier."""

    @abstractmethod
    def chat(
        self,
        messages: Sequence[Message],
        *,
        model: str | None = None,
        temperature: float = DEFAULT_TEMPERATURE,
        max_tokens: int | None = None,
    ) -> LLMResponse:
        """Send a chat completion request.

        Args:
            messages: OpenAI-format messages.
            model: Model override.
            temperature: Sampling temperature.
            max_tokens: Maximum generated tokens.

        Returns:
            A unified ``LLMResponse``.
        """

    @abstractmethod
    def estimate_cost(self, usage: Usage, model: str | None = None) -> float:
        """Estimate USD cost for the given usage.

        Args:
            usage: Token usage for the call.
            model: Model name; defaults to the provider default.

        Returns:
            Estimated cost in USD.
        """


class OpenAICompatibleProvider(LLMProvider):
    """LLM provider that calls an OpenAI-compatible chat completions API."""

    def __init__(
        self,
        *,
        name: str,
        api_key: str,
        base_url: str,
        default_model: str,
        pricing: Mapping[str, ModelPricing],
        timeout: float = DEFAULT_TIMEOUT_SECONDS,
    ) -> None:
        """Initialize the provider.

        Args:
            name: Provider identifier.
            api_key: API key; never logged.
            base_url: OpenAI-compatible base URL.
            default_model: Model used when no model is supplied.
            pricing: Model-to-pricing mapping.
            timeout: Request timeout in seconds.

        Raises:
            ValueError: If a required value is empty or invalid.
        """
        if not api_key.strip():
            raise ValueError("api_key 不能为空")
        if not base_url.startswith(("http://", "https://")):
            raise ValueError("base_url 必须是 http(s) URL")
        if not default_model.strip():
            raise ValueError("default_model 不能为空")
        if default_model not in pricing:
            raise ValueError(f"pricing 缺少默认模型 {default_model!r}")
        if timeout <= 0:
            raise ValueError("timeout 必须大于 0")

        self._name = name
        self._api_key = api_key
        self._base_url = base_url.rstrip("/")
        self._default_model = default_model
        self._pricing = dict(pricing)
        self._timeout = timeout

    @property
    def name(self) -> str:
        """Return the provider identifier."""
        return self._name

    @property
    def default_model(self) -> str:
        """Return the default model name."""
        return self._default_model

    def chat(
        self,
        messages: Sequence[Message],
        *,
        model: str | None = None,
        temperature: float = DEFAULT_TEMPERATURE,
        max_tokens: int | None = None,
    ) -> LLMResponse:
        """Send a chat completion request.

        Args:
            messages: OpenAI-format messages.
            model: Model override.
            temperature: Sampling temperature.
            max_tokens: Maximum generated tokens.

        Returns:
            A unified ``LLMResponse``.

        Raises:
            ValueError: If the request parameters are invalid.
            LLMError: If the API request fails.
        """
        if not messages:
            raise ValueError("messages 不能为空")
        if not 0 <= temperature <= 2:
            raise ValueError("temperature 必须在 0-2 之间")
        if max_tokens is not None and max_tokens <= 0:
            raise ValueError("max_tokens 必须大于 0")

        used_model = model or self._default_model
        payload: dict[str, Any] = {
            "model": used_model,
            "messages": list(messages),
            "temperature": temperature,
        }
        if max_tokens is not None:
            payload["max_tokens"] = max_tokens

        url = f"{self._base_url}/chat/completions"
        headers = {
            "Authorization": f"Bearer {self._api_key}",
            "Content-Type": "application/json",
            "Accept": "application/json",
        }

        try:
            with httpx.Client(timeout=self._timeout) as client:
                response = client.post(url, headers=headers, json=payload)
                response.raise_for_status()
        except httpx.HTTPStatusError as exc:
            status = exc.response.status_code
            body = exc.response.text[:500]
            retryable = status in RETRYABLE_STATUS_CODES or status >= 500
            raise LLMError(
                f"API 返回 HTTP {status}: {body}",
                status_code=status,
                retryable=retryable,
            ) from exc
        except httpx.TimeoutException as exc:
            raise LLMError("LLM 请求超时", retryable=True) from exc
        except httpx.TransportError as exc:
            raise LLMError(f"LLM 网络错误: {exc}", retryable=True) from exc
        except httpx.HTTPError as exc:
            raise LLMError(f"LLM HTTP 错误: {exc}", retryable=True) from exc

        try:
            data = response.json()
        except ValueError as exc:
            raise LLMError("LLM 响应不是合法 JSON", retryable=True) from exc

        if not isinstance(data, dict):
            raise LLMError("LLM 响应顶层必须是 JSON 对象", retryable=True)

        content = self._extract_content(data)
        if not content.strip():
            raise LLMError("LLM 响应 content 为空", retryable=True)

        usage = self._extract_usage(data, messages, content)
        cost_usd = self.estimate_cost(usage, model=used_model)
        response_model = data.get("model")

        response = LLMResponse(
            content=content,
            usage=usage,
            model=response_model if isinstance(response_model, str) else used_model,
            provider=self._name,
            cost_usd=cost_usd,
        )
        # 仅在请求成功并解析出 content 后记账，失败重试不会重复计数。
        tracker.record(usage, self._name)
        return response

    def estimate_cost(self, usage: Usage, model: str | None = None) -> float:
        """Estimate USD cost for this provider.

        Args:
            usage: Token usage for the call.
            model: Model name; defaults to the provider default.

        Returns:
            Estimated cost in USD.
        """
        model_name = model or self._default_model
        pricing = self._pricing.get(model_name)
        if pricing is None:
            LOGGER.warning(
                "未知模型 %s，使用默认模型 %s 的价格估算",
                model_name,
                self._default_model,
            )
            pricing = self._pricing[self._default_model]

        return calculate_cost(
            usage,
            pricing.input_per_1m_usd,
            pricing.output_per_1m_usd,
        )

    @staticmethod
    def _extract_content(data: Mapping[str, Any]) -> str:
        """Extract assistant text from an OpenAI-format response."""
        choices = data.get("choices")
        if not isinstance(choices, list) or not choices:
            raise LLMError("LLM 响应缺少 choices", retryable=True)

        first = choices[0]
        if not isinstance(first, dict):
            raise LLMError("LLM 响应 choices 格式非法", retryable=True)

        message = first.get("message")
        if not isinstance(message, dict):
            raise LLMError("LLM 响应缺少 message", retryable=True)

        content = message.get("content")
        if isinstance(content, str):
            return content
        if isinstance(content, list):
            parts: list[str] = []
            for item in content:
                if isinstance(item, dict) and isinstance(item.get("text"), str):
                    parts.append(item["text"])
            return "".join(parts)

        return ""

    @staticmethod
    def _extract_usage(
        data: Mapping[str, Any],
        messages: Sequence[Message],
        content: str,
    ) -> Usage:
        """Read API usage, falling back to a local estimate."""
        usage_data = data.get("usage")
        if isinstance(usage_data, dict):
            prompt_tokens = OpenAICompatibleProvider._as_int(
                usage_data.get("prompt_tokens")
            )
            completion_tokens = OpenAICompatibleProvider._as_int(
                usage_data.get("completion_tokens")
            )
            if prompt_tokens or completion_tokens:
                return Usage(
                    prompt_tokens=prompt_tokens,
                    completion_tokens=completion_tokens,
                    estimated=False,
                )

        return Usage(
            prompt_tokens=estimate_messages_tokens(messages),
            completion_tokens=estimate_tokens(content),
            estimated=True,
        )

    @staticmethod
    def _as_int(value: Any) -> int:
        """Convert an API token count to a non-negative integer."""
        try:
            return max(0, int(value))
        except (TypeError, ValueError):
            return 0


def create_provider(
    provider_name: str | None = None,
    *,
    api_key: str | None = None,
    model: str | None = None,
    base_url: str | None = None,
    timeout: float = DEFAULT_TIMEOUT_SECONDS,
) -> OpenAICompatibleProvider:
    """Create a provider from environment variables.

    Args:
        provider_name: Provider override; defaults to ``LLM_PROVIDER`` or
            ``deepseek``.
        api_key: Explicit API key, primarily for tests.
        model: Model override; defaults to ``LLM_MODEL`` or the provider
            default.
        base_url: Base URL override; defaults to ``LLM_BASE_URL`` or the
            provider default.
        timeout: Request timeout in seconds.

    Returns:
        A configured ``OpenAICompatibleProvider``.

    Raises:
        ValueError: If the provider is unknown or the API key is missing.
    """
    name = (provider_name or os.getenv("LLM_PROVIDER", DEFAULT_PROVIDER)).strip().lower()
    spec = PROVIDER_SPECS.get(name)
    if spec is None:
        supported = ", ".join(sorted(PROVIDER_SPECS))
        raise ValueError(f"未知 LLM_PROVIDER: {name!r}，可选: {supported}")

    resolved_key = api_key or os.getenv(spec.api_key_env)
    if not resolved_key and spec.fallback_api_key_env:
        resolved_key = os.getenv(spec.fallback_api_key_env)
    if not resolved_key:
        env_hint = spec.api_key_env
        if spec.fallback_api_key_env:
            env_hint += f" 或 {spec.fallback_api_key_env}"
        raise ValueError(f"缺少 API Key：请设置 {env_hint}")

    resolved_model = model or os.getenv("LLM_MODEL") or spec.default_model
    resolved_base_url = base_url or os.getenv("LLM_BASE_URL") or spec.base_url

    LOGGER.info(
        "创建 LLM 客户端 provider=%s model=%s timeout=%.0fs",
        name,
        resolved_model,
        timeout,
    )

    return OpenAICompatibleProvider(
        name=name,
        api_key=resolved_key,
        base_url=resolved_base_url,
        default_model=resolved_model,
        pricing=spec.pricing,
        timeout=timeout,
    )


def chat_with_retry(
    provider: LLMProvider,
    messages: Sequence[Message],
    *,
    model: str | None = None,
    temperature: float = DEFAULT_TEMPERATURE,
    max_tokens: int | None = None,
    max_attempts: int = DEFAULT_MAX_ATTEMPTS,
    base_delay: float = 1.0,
    max_delay: float = 10.0,
) -> LLMResponse:
    """Call a provider with exponential-backoff retries.

    Args:
        provider: Provider implementation.
        messages: OpenAI-format messages.
        model: Model override.
        temperature: Sampling temperature.
        max_tokens: Maximum generated tokens.
        max_attempts: Total attempts, including the first one.
        base_delay: Delay before the first retry, in seconds.
        max_delay: Upper bound for a single delay, in seconds.

    Returns:
        The successful ``LLMResponse``.

    Raises:
        ValueError: If retry settings are invalid.
        LLMError: If all attempts fail or the error is not retryable.
    """
    if max_attempts < 1:
        raise ValueError("max_attempts 必须大于等于 1")
    if base_delay < 0 or max_delay < 0:
        raise ValueError("重试间隔不能为负数")

    last_error: LLMError | None = None
    for attempt in range(1, max_attempts + 1):
        try:
            response = provider.chat(
                messages,
                model=model,
                temperature=temperature,
                max_tokens=max_tokens,
            )
        except LLMError as exc:
            last_error = exc
            if not exc.retryable:
                LOGGER.error("LLM 调用失败且不可重试: %s", exc)
                raise
            if attempt >= max_attempts:
                LOGGER.error(
                    "LLM 调用失败，已达最大尝试次数 %d: %s",
                    max_attempts,
                    exc,
                )
                raise

            delay = min(max_delay, base_delay * (2 ** (attempt - 1)))
            LOGGER.warning(
                "LLM 调用失败（第 %d/%d 次）: %s；%.1f 秒后重试",
                attempt,
                max_attempts,
                exc,
                delay,
            )
            time.sleep(delay)
            continue

        LOGGER.info(
            "LLM 调用成功 provider=%s model=%s prompt_tokens=%d "
            "completion_tokens=%d estimated=%s cost_usd=%.6f",
            response.provider,
            response.model,
            response.usage.prompt_tokens,
            response.usage.completion_tokens,
            response.usage.estimated,
            response.cost_usd,
        )
        return response

    if last_error is not None:
        raise last_error
    raise RuntimeError("chat_with_retry 未执行任何尝试")


def chat(
    prompt: str,
    *,
    system: str | None = None,
    provider: LLMProvider | None = None,
    model: str | None = None,
    temperature: float = DEFAULT_TEMPERATURE,
    max_tokens: int | None = None,
) -> tuple[str, Usage]:
    """Send one prompt and return ``(text, usage)``.

    Args:
        prompt: User prompt.
        system: Optional system prompt.
        provider: Provider instance; created from the environment when omitted.
        model: Model override.
        temperature: Sampling temperature.
        max_tokens: Maximum generated tokens.

    Returns:
        A tuple of assistant text and token usage.

    Raises:
        ValueError: If ``prompt`` is empty.
        LLMError: If the request fails after retries.
    """
    if not prompt.strip():
        raise ValueError("prompt 不能为空")

    client = provider or create_provider()
    messages: list[Message] = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})

    response = chat_with_retry(
        client,
        messages,
        model=model,
        temperature=temperature,
        max_tokens=max_tokens,
    )
    return response.content, response.usage


def _parse_json_object(text: str) -> dict[str, Any]:
    """Extract one JSON object from raw model output."""
    candidate = text.strip()
    try:
        payload = json.loads(candidate)
    except json.JSONDecodeError:
        start = candidate.find("{")
        end = candidate.rfind("}")
        if start < 0 or end <= start:
            raise LLMError("LLM 响应中没有 JSON 对象")
        try:
            payload = json.loads(candidate[start : end + 1])
        except json.JSONDecodeError as exc:
            raise LLMError(f"LLM 响应不是合法 JSON: {exc}") from exc

    if not isinstance(payload, dict):
        raise LLMError("LLM 响应必须是 JSON 对象")
    return payload


def chat_json(
    prompt: str,
    *,
    system: str | None = None,
    provider: LLMProvider | None = None,
    model: str | None = None,
    temperature: float = 0.0,
    max_tokens: int | None = None,
) -> tuple[dict[str, Any], Usage]:
    """Send one prompt and parse the reply as a JSON object.

    Args:
        prompt: User prompt.
        system: Optional system prompt; defaults to a JSON-only instruction.
        provider: Provider instance; created from the environment when omitted.
        model: Model override.
        temperature: Sampling temperature, 0 by default for stable output.
        max_tokens: Maximum generated tokens.

    Returns:
        A tuple of parsed JSON object and token usage.

    Raises:
        ValueError: If ``prompt`` is empty.
        LLMError: If the request fails or the reply is not a JSON object.
    """
    instruction = system or "只输出一个 JSON 对象，不要 Markdown 代码块或额外解释。"
    text, usage = chat(
        prompt,
        system=instruction,
        provider=provider,
        model=model,
        temperature=temperature,
        max_tokens=max_tokens,
    )
    return _parse_json_object(text), usage


def quick_chat(
    prompt: str,
    *,
    system: str | None = None,
    provider: LLMProvider | None = None,
    model: str | None = None,
    temperature: float = DEFAULT_TEMPERATURE,
    max_tokens: int | None = None,
) -> str:
    """Send one prompt and return the assistant text.

    Args:
        prompt: User prompt.
        system: Optional system prompt.
        provider: Provider instance; created from the environment when omitted.
        model: Model override.
        temperature: Sampling temperature.
        max_tokens: Maximum generated tokens.

    Returns:
        Assistant response content.

    Raises:
        ValueError: If ``prompt`` is empty.
        LLMError: If the request fails after retries.
    """
    text, _ = chat(
        prompt,
        system=system,
        provider=provider,
        model=model,
        temperature=temperature,
        max_tokens=max_tokens,
    )
    return text


class _FlakyProvider(LLMProvider):
    """Test provider that fails twice before succeeding."""

    def __init__(self) -> None:
        """Initialize the attempt counter."""
        self.attempts = 0

    @property
    def name(self) -> str:
        """Return the test provider name."""
        return "flaky"

    def chat(
        self,
        messages: Sequence[Message],
        *,
        model: str | None = None,
        temperature: float = DEFAULT_TEMPERATURE,
        max_tokens: int | None = None,
    ) -> LLMResponse:
        """Fail twice, then return a fixed response."""
        self.attempts += 1
        if self.attempts < 3:
            raise LLMError("模拟临时故障", retryable=True)
        return LLMResponse(
            content="retry-ok",
            usage=Usage(prompt_tokens=1, completion_tokens=1),
            model=model or "flaky-model",
            provider=self.name,
        )

    def estimate_cost(self, usage: Usage, model: str | None = None) -> float:
        """Return zero cost for the fake provider."""
        return 0.0


def _run_self_test() -> None:
    """Run offline checks and an optional live request."""
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )

    sample_text = "大语言模型（LLM）可以理解和生成自然语言。"
    LOGGER.info(
        "estimate_tokens(%r) = %d",
        sample_text,
        estimate_tokens(sample_text),
    )

    sample_usage = Usage(prompt_tokens=1_000, completion_tokens=500)
    for provider_name in sorted(PROVIDER_SPECS):
        cost = estimate_cost(provider_name, sample_usage)
        LOGGER.info("%s 参考成本: $%.6f", provider_name, cost)

    flaky = _FlakyProvider()
    retry_response = chat_with_retry(
        flaky,
        [{"role": "user", "content": "ping"}],
        max_attempts=3,
        base_delay=0.0,
        max_delay=0.0,
    )
    LOGGER.info(
        "重试自测通过: attempts=%d content=%s",
        flaky.attempts,
        retry_response.content,
    )

    name = os.getenv("LLM_PROVIDER", DEFAULT_PROVIDER).strip().lower()
    spec = PROVIDER_SPECS.get(name)
    if spec is None:
        LOGGER.error("未知 LLM_PROVIDER=%s，跳过真实调用", name)
        return

    has_key = bool(os.getenv(spec.api_key_env))
    if not has_key and spec.fallback_api_key_env:
        has_key = bool(os.getenv(spec.fallback_api_key_env))
    if not has_key:
        LOGGER.warning("未设置 %s，跳过真实 API 调用", spec.api_key_env)
        return

    LOGGER.info("开始真实调用 provider=%s", name)
    try:
        answer = quick_chat("用一句话解释什么是 RAG。")
    except LLMError as exc:
        LOGGER.error("真实调用失败: %s", exc)
        return

    LOGGER.info("模型回答: %s", answer)


if __name__ == "__main__":
    _run_self_test()
